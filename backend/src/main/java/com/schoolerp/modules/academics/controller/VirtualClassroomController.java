package com.schoolerp.modules.academics.controller;

import com.schoolerp.common.response.ApiResponse;
import com.schoolerp.modules.academics.dto.*;
import com.schoolerp.modules.academics.service.VirtualClassroomService;
import lombok.RequiredArgsConstructor;
import org.springframework.format.annotation.DateTimeFormat;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.security.core.Authentication;
import org.springframework.web.bind.annotation.*;

import java.time.LocalDate;
import java.util.List;
import java.util.UUID;

@RestController
@RequestMapping("/api/v1/academics/virtual-classrooms")
@RequiredArgsConstructor
public class VirtualClassroomController {

    private final VirtualClassroomService virtualService;

    @PostMapping("/auto-generate-daily")
    @PreAuthorize("hasAnyRole('SUPER_ADMIN', 'ADMIN', 'PRINCIPAL', 'TEACHER')")
    public ResponseEntity<ApiResponse<List<VirtualClassroomSessionDTO>>> autoGenerateDailySessions(
            @RequestBody AutoGenerateVirtualSessionsRequest request) {
        List<VirtualClassroomSessionDTO> sessions = virtualService.autoGenerateDailySessions(request);
        return ResponseEntity.status(HttpStatus.CREATED)
                .body(ApiResponse.ok("Virtual classroom timetable sessions generated successfully", sessions));
    }

    @GetMapping("/student-feed")
    @PreAuthorize("hasAnyRole('SUPER_ADMIN', 'ADMIN', 'PRINCIPAL', 'TEACHER', 'STUDENT', 'PARENT', 'STAFF')")
    public ResponseEntity<ApiResponse<List<VirtualClassroomSessionDTO>>> getStudentDailyFeed(
            @RequestParam String className,
            @RequestParam(defaultValue = "A") String sectionName,
            @RequestParam(required = false) @DateTimeFormat(iso = DateTimeFormat.ISO.DATE) LocalDate date) {
        List<VirtualClassroomSessionDTO> feed = virtualService.getStudentDailyFeed(className, sectionName, date);
        return ResponseEntity.ok(ApiResponse.ok("Student daily virtual classroom schedule retrieved", feed));
    }

    @PostMapping("/{id}/start")
    @PreAuthorize("hasAnyRole('SUPER_ADMIN', 'ADMIN', 'PRINCIPAL', 'TEACHER')")
    public ResponseEntity<ApiResponse<VirtualClassroomSessionDTO>> startSession(@PathVariable UUID id) {
        VirtualClassroomSessionDTO started = virtualService.startSession(id);
        return ResponseEntity.ok(ApiResponse.ok("Virtual classroom session is now LIVE", started));
    }

    @PostMapping("/{id}/end")
    @PreAuthorize("hasAnyRole('SUPER_ADMIN', 'ADMIN', 'PRINCIPAL', 'TEACHER')")
    public ResponseEntity<ApiResponse<VirtualClassroomSessionDTO>> endSession(
            @PathVariable UUID id,
            @RequestParam(required = false) String recordingUrl) {
        VirtualClassroomSessionDTO ended = virtualService.endSession(id, recordingUrl);
        return ResponseEntity.ok(ApiResponse.ok("Virtual classroom session concluded successfully", ended));
    }

    @PostMapping("/async-catchup/submit")
    @PreAuthorize("hasAnyRole('SUPER_ADMIN', 'STUDENT', 'PARENT', 'TEACHER')")
    public ResponseEntity<ApiResponse<AsyncCatchupSubmissionDTO>> submitAsyncCatchup(
            @RequestBody SubmitAsyncCatchupRequest request) {
        AsyncCatchupSubmissionDTO sub = virtualService.submitAsyncCatchup(request);
        return ResponseEntity.status(HttpStatus.CREATED)
                .body(ApiResponse.ok("Asynchronous proof-of-learning catch-up submitted successfully", sub));
    }

    @PutMapping("/async-catchup/{id}/verify")
    @PreAuthorize("hasAnyRole('SUPER_ADMIN', 'ADMIN', 'PRINCIPAL', 'TEACHER')")
    public ResponseEntity<ApiResponse<AsyncCatchupSubmissionDTO>> verifyAsyncCatchup(
            @PathVariable UUID id,
            Authentication auth) {
        String teacherName = (auth != null) ? auth.getName() : "Faculty Evaluator";
        AsyncCatchupSubmissionDTO verified = virtualService.verifyAsyncCatchup(id, teacherName);
        return ResponseEntity.ok(ApiResponse.ok("Async catch-up verified; attendance normalized to EXCUSED_ASYNC_COMPLETED", verified));
    }
}

