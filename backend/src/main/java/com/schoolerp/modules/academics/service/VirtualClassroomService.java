package com.schoolerp.modules.academics.service;

import com.schoolerp.common.context.TenantContext;
import com.schoolerp.modules.academics.dto.*;
import com.schoolerp.modules.academics.entity.AsyncCatchupSubmission;
import com.schoolerp.modules.academics.entity.VirtualClassroomSession;
import com.schoolerp.modules.academics.repository.AsyncCatchupSubmissionRepository;
import com.schoolerp.modules.academics.repository.VirtualClassroomSessionRepository;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.*;
import java.util.stream.Collectors;

@Service
@RequiredArgsConstructor
@Slf4j
public class VirtualClassroomService {

    private final VirtualClassroomSessionRepository sessionRepository;
    private final AsyncCatchupSubmissionRepository asyncRepository;

    @Transactional
    public List<VirtualClassroomSessionDTO> autoGenerateDailySessions(AutoGenerateVirtualSessionsRequest request) {
        String tenantId = Optional.ofNullable(TenantContext.getTenantId()).orElse("tenant_apex_mumbai_01");
        LocalDate date = request.getSessionDate() != null ? request.getSessionDate() : LocalDate.now();
        String provider = request.getMeetingProvider() != null ? request.getMeetingProvider() : "JITSI_WEBRTC";

        List<VirtualClassroomSession> generated = new ArrayList<>();

        if (request.getPeriods() != null && !request.getPeriods().isEmpty()) {
            for (var p : request.getPeriods()) {
                String roomCode = String.format("%s-%s%s-%s-P%d",
                        tenantId.replace("tenant_", "").toUpperCase(),
                        request.getClassName().replace(" ", ""),
                        request.getSectionName().replace(" ", ""),
                        p.getSubjectName().substring(0, Math.min(4, p.getSubjectName().length())).toUpperCase(),
                        p.getPeriodNumber());

                String meetingUrl;
                if ("ZOOM_EDUCATION".equalsIgnoreCase(provider)) {
                    meetingUrl = "https://zoom.us/j/" + (1000000000L + Math.abs(roomCode.hashCode() % 9000000000L));
                } else if ("GOOGLE_MEET".equalsIgnoreCase(provider)) {
                    meetingUrl = "https://meet.google.com/" + roomCode.toLowerCase().replace("_", "-");
                } else {
                    // Default Jitsi WebRTC: Fully in-app, encrypted, zero 3rd party license cost
                    meetingUrl = "https://meet.jit.si/" + roomCode;
                }

                VirtualClassroomSession session = VirtualClassroomSession.builder()
                        .tenantId(tenantId)
                        .className(request.getClassName())
                        .sectionName(request.getSectionName())
                        .subjectName(p.getSubjectName())
                        .teacherName(p.getTeacherName())
                        .sessionDate(date)
                        .periodNumber(p.getPeriodNumber())
                        .startTime(p.getStartTime())
                        .endTime(p.getEndTime())
                        .meetingProvider(provider)
                        .joinMeetingUrl(meetingUrl)
                        .meetingRoomCode(roomCode)
                        .sessionStatus("SCHEDULED")
                        .createdAt(LocalDateTime.now())
                        .build();

                generated.add(sessionRepository.save(session));
            }
        }

        log.info("Auto-generated {} virtual classroom sessions for {} {} on {}", generated.size(), request.getClassName(), request.getSectionName(), date);
        return generated.stream().map(this::toDto).collect(Collectors.toList());
    }

    @Transactional(readOnly = true)
    public List<VirtualClassroomSessionDTO> getStudentDailyFeed(String className, String sectionName, LocalDate date) {
        String tenantId = Optional.ofNullable(TenantContext.getTenantId()).orElse("tenant_apex_mumbai_01");
        LocalDate targetDate = (date != null) ? date : LocalDate.now();

        return sessionRepository.findByTenantIdAndSessionDateAndClassNameAndSectionNameOrderByPeriodNumberAsc(
                tenantId, targetDate, className, sectionName)
                .stream()
                .map(this::toDto)
                .collect(Collectors.toList());
    }

    @Transactional
    public VirtualClassroomSessionDTO startSession(UUID sessionId) {
        VirtualClassroomSession session = sessionRepository.findById(sessionId)
                .orElseThrow(() -> new IllegalArgumentException("Virtual classroom session not found: " + sessionId));

        session.setSessionStatus("LIVE_IN_PROGRESS");
        session.setStartedAt(LocalDateTime.now());
        VirtualClassroomSession saved = sessionRepository.save(session);

        log.info("Virtual classroom session #{} for {} is now LIVE: {}", session.getPeriodNumber(), session.getSubjectName(), session.getMeetingRoomCode());
        return toDto(saved);
    }

    @Transactional
    public VirtualClassroomSessionDTO endSession(UUID sessionId, String recordingUrl) {
        VirtualClassroomSession session = sessionRepository.findById(sessionId)
                .orElseThrow(() -> new IllegalArgumentException("Virtual classroom session not found: " + sessionId));

        session.setSessionStatus("CONCLUDED");
        session.setConcludedAt(LocalDateTime.now());
        if (recordingUrl != null && !recordingUrl.isBlank()) {
            session.setRecordingUrl(recordingUrl);
        }

        VirtualClassroomSession saved = sessionRepository.save(session);
        log.info("Virtual classroom session #{} for {} CONCLUDED", session.getPeriodNumber(), session.getSubjectName());
        return toDto(saved);
    }

    @Transactional
    public AsyncCatchupSubmissionDTO submitAsyncCatchup(SubmitAsyncCatchupRequest request) {
        VirtualClassroomSession session = sessionRepository.findById(request.getSessionId())
                .orElseThrow(() -> new IllegalArgumentException("Session not found: " + request.getSessionId()));

        AsyncCatchupSubmission sub = AsyncCatchupSubmission.builder()
                .sessionId(session.getId())
                .studentId(request.getStudentId())
                .studentName(request.getStudentName())
                .submissionDate(LocalDate.now())
                .materialReviewedTitle(request.getMaterialReviewedTitle())
                .proofOfLearningResponseText(request.getProofOfLearningResponseText())
                .quizScore(request.getQuizScore() > 0 ? request.getQuizScore() : 100.0)
                .status("SUBMITTED")
                .submittedAt(LocalDateTime.now())
                .build();

        AsyncCatchupSubmission saved = asyncRepository.save(sub);
        log.info("Student {} submitted async catchup for virtual session {}: '{}'", request.getStudentName(), session.getSubjectName(), request.getMaterialReviewedTitle());

        return toAsyncDto(saved);
    }

    @Transactional
    public AsyncCatchupSubmissionDTO verifyAsyncCatchup(UUID submissionId, String teacherName) {
        AsyncCatchupSubmission sub = asyncRepository.findById(submissionId)
                .orElseThrow(() -> new IllegalArgumentException("Async catchup submission not found: " + submissionId));

        sub.setStatus("VERIFIED_ATTENDANCE_NORMALIZED");
        sub.setVerifiedByTeacherName(teacherName);
        sub.setVerifiedAt(LocalDateTime.now());

        AsyncCatchupSubmission saved = asyncRepository.save(sub);
        log.info("Teacher {} verified async catchup for student {}. Attendance normalized to EXCUSED_ASYNC_COMPLETED", teacherName, sub.getStudentName());

        return toAsyncDto(saved);
    }

    private VirtualClassroomSessionDTO toDto(VirtualClassroomSession s) {
        return VirtualClassroomSessionDTO.builder()
                .id(s.getId())
                .className(s.getClassName())
                .sectionName(s.getSectionName())
                .subjectName(s.getSubjectName())
                .teacherName(s.getTeacherName())
                .sessionDate(s.getSessionDate())
                .periodNumber(s.getPeriodNumber())
                .startTime(s.getStartTime())
                .endTime(s.getEndTime())
                .meetingProvider(s.getMeetingProvider())
                .joinMeetingUrl(s.getJoinMeetingUrl())
                .meetingRoomCode(s.getMeetingRoomCode())
                .sessionStatus(s.getSessionStatus())
                .totalStudentsJoined(s.getTotalStudentsJoined())
                .recordingUrl(s.getRecordingUrl())
                .startedAt(s.getStartedAt())
                .concludedAt(s.getConcludedAt())
                .build();
    }

    private AsyncCatchupSubmissionDTO toAsyncDto(AsyncCatchupSubmission a) {
        return AsyncCatchupSubmissionDTO.builder()
                .id(a.getId())
                .sessionId(a.getSessionId())
                .studentId(a.getStudentId())
                .studentName(a.getStudentName())
                .submissionDate(a.getSubmissionDate())
                .materialReviewedTitle(a.getMaterialReviewedTitle())
                .proofOfLearningResponseText(a.getProofOfLearningResponseText())
                .quizScore(a.getQuizScore())
                .verifiedByTeacherName(a.getVerifiedByTeacherName())
                .status(a.getStatus())
                .submittedAt(a.getSubmittedAt())
                .verifiedAt(a.getVerifiedAt())
                .build();
    }
}

